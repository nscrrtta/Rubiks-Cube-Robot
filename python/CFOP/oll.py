class OLL:

    def solve_OLL(self, cubes: list[Cube]):
        for cube in cubes:
            self._solve_OLL(cube)

    def _solve_OLL(self, cube: Cube):

        def get_char(i: int) -> str:
            t, f = ('x', 'o') if Fc.U1 <= i <= Fc.U9 else ('-', ' ')
            return t if cube.colours[i] == cube.colours[Fc.U5] else f

        indices = [
                   Fc.B3, Fc.B2, Fc.B1,
            Fc.L1, Fc.U1, Fc.U2, Fc.U3, Fc.R3,
            Fc.L2, Fc.U4, Fc.U5, Fc.U6, Fc.R2,
            Fc.L3, Fc.U7, Fc.U8, Fc.U9, Fc.R1,
                   Fc.F1, Fc.F2, Fc.F3
        ]

        for _ in range(4):
            diagram = ''.join(get_char(i) for i in indices)
            if diagram in OLL_DICT:
                break
            cube.rotate_y_axis()

        for move in OLL_DICT[diagram]:
            cube.make_move(move)


